"""One error shape for every failure (W2; plan §4.2.5, EIR-02, NFR-SEC-01).

The status table is fixed, the message is a constant per code, and the request
id is generated by the server. Nothing from the request - a field name, an
input value, a token, a code - and nothing from the server - a message, SQL, a
path - may reach a response or a log line.
"""

from __future__ import annotations

import logging
from pathlib import Path

import pytest

pytest.importorskip("fastapi")

from backend.api.errors import (  # noqa: E402
    ERROR_MESSAGES,
    MAX_BODY_BYTES,
    ApiError,
    code_for_status,
)
from tests.api_fixtures import ApiHarness, ApiResponse, build_harness  # noqa: E402

SECRET_LOOKING = "sk-live-not-a-real-secret-0000"


@pytest.fixture()
def harness(tmp_path: Path) -> ApiHarness:
    return build_harness(tmp_path)


def _error(response: ApiResponse) -> dict[str, object]:
    body = response.json()
    assert set(body) == {"error"}
    error = body["error"]
    assert set(error) == {"code", "message", "request_id"}
    return error


def test_the_error_table_is_exactly_the_agreed_statuses() -> None:
    """One code per status; no 200, no 302, no invented code."""
    assert {code: status for code, (status, _message) in ERROR_MESSAGES.items()} == {
        "UNAUTHENTICATED": 401,
        "FORBIDDEN": 403,
        "NOT_FOUND": 404,
        "CONFLICT": 409,
        "INVALID_REQUEST": 422,
        "IDEMPOTENCY_KEY_REUSED": 422,
        "RATE_LIMITED": 429,
        "INTERNAL_ERROR": 500,
    }
    assert code_for_status(405) == "INVALID_REQUEST"
    assert code_for_status(418) == "INVALID_REQUEST"
    assert code_for_status(503) == "INTERNAL_ERROR"


def test_an_unknown_code_is_refused_at_construction() -> None:
    with pytest.raises(ValueError):
        ApiError("TEAPOT")


def test_unknown_path_is_a_404_with_the_uniform_body(
    harness: ApiHarness,
) -> None:
    response = harness.call("GET", "/no-such-route")
    assert response.status == 404
    error = _error(response)
    assert error["code"] == "NOT_FOUND"
    assert error["message"] == ERROR_MESSAGES["NOT_FOUND"][1]


def test_a_disallowed_method_maps_onto_the_table(harness: ApiHarness) -> None:
    """405 is outside the table, so it becomes 422 with no ``Allow`` header."""
    response = harness.call("DELETE", "/healthz")
    assert response.status == 422
    assert _error(response)["code"] == "INVALID_REQUEST"
    assert response.header("allow") is None


def test_request_id_is_per_response_and_appears_in_the_body(
    harness: ApiHarness,
) -> None:
    first = harness.call("GET", "/no-such-route")
    second = harness.call("GET", "/no-such-route")
    assert first.header("x-request-id")
    assert first.header("x-request-id") != second.header("x-request-id")
    assert _error(first)["request_id"] == first.header("x-request-id")


def test_an_unknown_field_is_a_422_and_is_not_echoed(
    harness: ApiHarness,
) -> None:
    """The framework's validation detail can echo input; it is never sent."""
    response = harness.call(
        "POST",
        "/auth/otp",
        json_body={"roll_number": "R-VOL", "unexpected_field": SECRET_LOOKING},
    )
    assert response.status == 422
    body = response.body.decode("utf-8")
    assert "unexpected_field" not in body
    assert SECRET_LOOKING not in body
    assert _error(response)["code"] == "INVALID_REQUEST"


def test_a_rejected_code_is_not_echoed_in_the_validation_body(
    harness: ApiHarness,
) -> None:
    """A body-level rejection must not repeat the code the client sent."""
    response = harness.call(
        "POST",
        "/auth/verify",
        json_body={"roll_number": "R-VOL", "code": 123456},
    )
    assert response.status == 422
    assert b"123456" not in response.body
    assert _error(response)["code"] == "INVALID_REQUEST"


def test_malformed_json_is_a_422(harness: ApiHarness) -> None:
    response = harness.call("POST", "/auth/otp", body=b'{"roll_number": ')
    assert response.status == 422
    assert _error(response)["code"] == "INVALID_REQUEST"


def test_an_oversized_declared_body_is_refused_before_parsing(
    harness: ApiHarness,
) -> None:
    """A declared body over the cap is a 422 and no route logic runs."""
    response = harness.call(
        "POST",
        "/auth/otp",
        json_body={"roll_number": "R-VOL"},
        content_length=MAX_BODY_BYTES + 1,
    )
    assert response.status == 422
    assert _error(response)["code"] == "INVALID_REQUEST"
    assert harness.sender.sent == ()


def test_an_unexpected_error_is_a_generic_500(
    harness: ApiHarness,
    monkeypatch: pytest.MonkeyPatch,
    caplog: pytest.LogCaptureFixture,
) -> None:
    """An internal failure says nothing and logs only the request id and type."""
    from backend.api import handlers

    def explode(*args: object, **kwargs: object) -> None:
        raise RuntimeError(f"boom {SECRET_LOOKING}")

    monkeypatch.setattr(handlers.auth, "request_otp", explode)
    with caplog.at_level(logging.ERROR, logger="asec.api"):
        response = harness.call(
            "POST", "/auth/otp", json_body={"roll_number": "R-VOL"}
        )

    assert response.status == 500
    error = _error(response)
    assert error["code"] == "INTERNAL_ERROR"
    assert error["message"] == ERROR_MESSAGES["INTERNAL_ERROR"][1]
    # The middleware re-raises after sending the handler's response.
    assert isinstance(response.raised, RuntimeError)

    body = response.body.decode("utf-8")
    assert SECRET_LOOKING not in body
    assert "boom" not in body
    assert "R-VOL" not in body
    assert SECRET_LOOKING not in caplog.text
    assert "boom" not in caplog.text
    assert "RuntimeError" in caplog.text
    assert str(response.header("x-request-id")) in caplog.text


def test_an_error_never_echoes_the_presented_token(harness: ApiHarness) -> None:
    response = harness.call(
        "GET", "/me", headers={"authorization": f"Bearer {SECRET_LOOKING}"}
    )
    assert response.status == 401
    assert SECRET_LOOKING not in response.body.decode("utf-8")
    assert _error(response)["code"] == "UNAUTHENTICATED"
