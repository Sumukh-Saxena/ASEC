CREATE TABLE source_message (
    id                      INTEGER PRIMARY KEY,
    source                  TEXT NOT NULL,
    source_message_id       TEXT NOT NULL,
    group_id                INTEGER NOT NULL,
    sender_person_id        INTEGER NULL,
    sender_discord_user_id  TEXT NULL,
    event_timestamp         TEXT NULL,
    received_at             TEXT NOT NULL,
    content                 TEXT NULL,
    reply_reference         TEXT NULL,
    raw_metadata            TEXT NULL,
    flag_late               INTEGER NOT NULL DEFAULT 0,
    flag_unmapped           INTEGER NOT NULL DEFAULT 0,
    flag_unknown_sender     INTEGER NOT NULL DEFAULT 0,
    flag_unclassified       INTEGER NOT NULL DEFAULT 0,
    CHECK (source = trim(source) AND length(source) > 0),
    CHECK (length(trim(source_message_id)) > 0),
    CHECK (length(trim(received_at)) > 0),
    CHECK (sender_discord_user_id IS NULL OR length(trim(sender_discord_user_id)) > 0),
    CHECK (event_timestamp IS NULL OR length(trim(event_timestamp)) > 0),
    CHECK (content IS NULL OR length(content) > 0),
    CHECK (reply_reference IS NULL OR length(trim(reply_reference)) > 0),
    CHECK (raw_metadata IS NULL OR length(trim(raw_metadata)) > 0),
    CHECK (flag_late IN (0, 1)),
    CHECK (flag_unmapped IN (0, 1)),
    CHECK (flag_unknown_sender IN (0, 1)),
    CHECK (flag_unclassified IN (0, 1)),
    UNIQUE (source, source_message_id),
    FOREIGN KEY (group_id) REFERENCES source_group(id) ON DELETE RESTRICT,
    FOREIGN KEY (sender_person_id) REFERENCES person(id) ON DELETE RESTRICT
);

CREATE TABLE message_reaction (
    id                      INTEGER PRIMARY KEY,
    message_id              INTEGER NOT NULL,
    reactor_discord_user_id TEXT NOT NULL,
    emoji                   TEXT NOT NULL,
    direction               TEXT NOT NULL,
    reacted_at              TEXT NULL,
    CHECK (length(trim(reactor_discord_user_id)) > 0),
    CHECK (length(trim(emoji)) > 0),
    CHECK (direction = trim(direction) AND length(direction) > 0),
    CHECK (reacted_at IS NULL OR length(trim(reacted_at)) > 0),
    FOREIGN KEY (message_id) REFERENCES source_message(id) ON DELETE RESTRICT
);
